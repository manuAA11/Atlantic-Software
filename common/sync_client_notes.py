"""Copy additive staff notes upgrade and its tests to all existing profiles."""
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]
MIGRATION = '20261030235749_client_staff_notes.sql'  # Generated by Supabase CLI.


def synchronize():
    source = ROOT / 'common' / 'client_notes.sql'
    shutil.copyfile(source, ROOT / 'supabase/migrations' / MIGRATION)
    for edition in ROOT.glob('GymSoft_*'):
        shutil.copyfile(source, edition / 'ACTUALIZAR_NOTAS_CLIENTES.sql')
        shutil.copyfile(source, edition / 'supabase/migrations' / MIGRATION)
        for name in ('client_notes.mjs', 'test_client_notes.py', 'client_notes_ui_smoke.py'):
            test = ROOT / 'common' / name
            if test.exists():
                shutil.copyfile(test, edition / 'tests' / name)


if __name__ == '__main__':
    synchronize()
