create or replace function public.admin_staff_clock(
    p_gym_id uuid,
    p_trainer_id bigint,
    p_action text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_trainer public.trainers%rowtype;
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin']::text[]
    ) then
        raise exception 'Solo el administrador puede controlar jornadas.'
            using errcode = '42501';
    end if;

    select t.* into v_trainer
    from public.trainers t
    where t.id = p_trainer_id
      and t.gym_id = p_gym_id
      and t.active = true;

    if not found then
        raise exception 'El trabajador no existe o está inactivo.'
            using errcode = '23503';
    end if;

    if upper(trim(p_action)) = 'IN' then
        if exists (
            select 1 from public.staff_shifts s
            where s.trainer_id = p_trainer_id
              and s.check_out_at is null
        ) then
            raise exception 'El trabajador ya tiene una jornada activa.'
                using errcode = '23505';
        end if;

        insert into public.staff_shifts(
            gym_id,
            trainer_id,
            hourly_rate_snapshot,
            recorded_by
        ) values (
            p_gym_id,
            p_trainer_id,
            v_trainer.hourly_rate,
            (select auth.uid())
        );
    elsif upper(trim(p_action)) = 'OUT' then
        update public.staff_shifts
        set check_out_at = now(), recorded_by = (select auth.uid())
        where trainer_id = p_trainer_id
          and gym_id = p_gym_id
          and check_out_at is null;

        if not found then
            raise exception 'El trabajador no tiene una jornada activa.'
                using errcode = 'P0002';
        end if;
    else
        raise exception 'La acción debe ser IN u OUT.'
            using errcode = '22023';
    end if;
end;
$$;

revoke all on function public.admin_staff_clock(uuid, bigint, text)
    from public, anon, authenticated;
grant execute on function public.admin_staff_clock(uuid, bigint, text)
    to authenticated;

create or replace function public.admin_staff_dashboard(
    p_gym_id uuid,
    p_date_from date,
    p_date_to date
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_result jsonb;
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin']::text[]
    ) then
        raise exception 'La información de personal es administrativa.'
            using errcode = '42501';
    end if;

    if p_date_from is null or p_date_to is null or p_date_from > p_date_to then
        raise exception 'El período de jornadas no es válido.'
            using errcode = '22023';
    end if;

    with shift_values as (
        select
            s.*,
            greatest(
                extract(epoch from (
                    coalesce(s.check_out_at, now()) - s.check_in_at
                ))::bigint,
                0
            ) as duration_seconds
        from public.staff_shifts s
        where s.gym_id = p_gym_id
          and (s.check_in_at at time zone 'America/Bogota')::date
              between p_date_from and p_date_to
    ), worker_values as (
        select
            t.*,
            coalesce((
                select sum(s.duration_seconds)
                from shift_values s
                where s.trainer_id = t.id
            ), 0)::bigint as period_seconds,
            coalesce((
                select round(sum(
                    s.duration_seconds * s.hourly_rate_snapshot / 3600.0
                ))::bigint
                from shift_values s
                where s.trainer_id = t.id
            ), 0)::bigint as estimated_pay,
            (
                select s.check_in_at
                from public.staff_shifts s
                where s.trainer_id = t.id
                  and s.check_out_at is null
                order by s.check_in_at desc
                limit 1
            ) as current_check_in
        from public.trainers t
        where t.gym_id = p_gym_id
    )
    select jsonb_build_object(
        'active_staff', (
            select count(*) from worker_values w where w.active = true
        ),
        'working_now', (
            select count(*) from worker_values w
            where w.current_check_in is not null
        ),
        'total_seconds', coalesce((
            select sum(w.period_seconds) from worker_values w
        ), 0),
        'estimated_payroll', coalesce((
            select sum(w.estimated_pay) from worker_values w
        ), 0),
        'workers', coalesce((
            select jsonb_agg(jsonb_build_object(
                'id', w.id,
                'name', w.name,
                'phone', w.phone,
                'email', w.email,
                'specialty', w.specialty,
                'hourly_rate', w.hourly_rate,
                'hire_date', w.hire_date,
                'notes', w.notes,
                'active', w.active,
                'current_check_in', w.current_check_in,
                'period_seconds', w.period_seconds,
                'estimated_pay', w.estimated_pay
            ) order by w.active desc, w.name)
            from worker_values w
        ), '[]'::jsonb),
        'shifts', coalesce((
            select jsonb_agg(jsonb_build_object(
                'id', s.id,
                'trainer_id', s.trainer_id,
                'trainer_name', t.name,
                'check_in_at', s.check_in_at,
                'check_out_at', s.check_out_at,
                'duration_seconds', s.duration_seconds,
                'hourly_rate', s.hourly_rate_snapshot,
                'estimated_pay', round(
                    s.duration_seconds * s.hourly_rate_snapshot / 3600.0
                )::bigint
            ) order by s.check_in_at desc)
            from shift_values s
            join public.trainers t on t.id = s.trainer_id
        ), '[]'::jsonb)
    ) into v_result;

    return v_result;
end;
$$;

revoke all on function public.admin_staff_dashboard(uuid, date, date)
    from public, anon, authenticated;
grant execute on function public.admin_staff_dashboard(uuid, date, date)
    to authenticated;

create or replace function public.admin_accounting_expenses(
    p_gym_id uuid,
    p_date_from date,
    p_date_to date
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_result jsonb;
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin']::text[]
    ) then
        raise exception 'La contabilidad es exclusiva del administrador.'
            using errcode = '42501';
    end if;

    if p_date_from is null or p_date_to is null or p_date_from > p_date_to then
        raise exception 'El período contable no es válido.'
            using errcode = '22023';
    end if;

    with expenses as (
        select
            e.*,
            coalesce(
                nullif(a.actor_email, ''),
                case
                    when e.recorded_by is null then 'Sistema'
                    else 'Usuario ' || left(e.recorded_by::text, 8)
                end
            ) as actor_email,
            coalesce(nullif(a.actor_role, ''), 'admin') as actor_role
        from public.accounting_expenses e
        left join lateral (
            select al.actor_email, al.actor_role
            from public.audit_logs al
            where al.gym_id = e.gym_id
              and al.entity_type = 'accounting_expenses'
              and al.entity_id = e.id::text
              and al.action = 'EGRESO_REGISTRADO'
            order by al.created_at asc, al.id asc
            limit 1
        ) a on true
        where e.gym_id = p_gym_id
          and e.expense_date between p_date_from and p_date_to
    )
    select jsonb_build_object(
        'total_expenses', coalesce((select sum(amount) from expenses), 0),
        'expense_count', (select count(*) from expenses),
        'by_category', coalesce((
            select jsonb_agg(jsonb_build_object(
                'label', grouped.category,
                'count', grouped.expense_count,
                'total', grouped.total
            ) order by grouped.total desc, grouped.category)
            from (
                select category, count(*) expense_count, sum(amount) total
                from expenses
                group by category
            ) grouped
        ), '[]'::jsonb),
        'expenses', coalesce((
            select jsonb_agg(jsonb_build_object(
                'id', e.id,
                'expense_date', e.expense_date,
                'category', e.category,
                'description', e.description,
                'vendor', e.vendor,
                'amount', e.amount,
                'payment_method', e.payment_method,
                'payment_reference', e.payment_reference,
                'receipt_reference', e.receipt_reference,
                'notes', e.notes,
                'actor_email', e.actor_email,
                'actor_role', e.actor_role,
                'created_at', e.created_at
            ) order by e.expense_date desc, e.id desc)
            from expenses e
        ), '[]'::jsonb)
    ) into v_result;

    return v_result;
end;
$$;

revoke all on function public.admin_accounting_expenses(uuid, date, date)
    from public, anon, authenticated;
grant execute on function public.admin_accounting_expenses(uuid, date, date)
