create or replace function private.write_staff_accounting_audit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_row jsonb;
    v_gym_id uuid;
    v_actor uuid;
    v_email text;
    v_role text;
    v_action text;
    v_summary text;
begin
    v_row := case
        when tg_op = 'DELETE' then to_jsonb(old)
        else to_jsonb(new)
    end;
    v_gym_id := (v_row ->> 'gym_id')::uuid;
    v_actor := coalesce(
        nullif(v_row ->> 'recorded_by', '')::uuid,
        nullif(v_row ->> 'created_by', '')::uuid,
        (select auth.uid())
    );

    select coalesce(gu.role, 'authenticated')
    into v_role
    from public.gym_users gu
    where gu.gym_id = v_gym_id
      and gu.user_id = v_actor
    limit 1;

    v_role := coalesce(v_role, 'system');
    v_email := coalesce(
        nullif(auth.jwt() ->> 'email', ''),
        case
            when v_actor is null then 'Sistema'
            else 'Usuario ' || left(v_actor::text, 8)
        end
    );

    if tg_table_name = 'accounting_expenses' then
        v_action := case tg_op
            when 'INSERT' then 'EGRESO_REGISTRADO'
            when 'UPDATE' then 'EGRESO_EDITADO'
            else 'EGRESO_ELIMINADO'
        end;
        v_summary := concat(
            coalesce(v_row ->> 'category', 'Egreso'),
            ' · $', coalesce(v_row ->> 'amount', '0'),
            ' · ', coalesce(v_row ->> 'description', '')
        );
    elsif tg_table_name = 'staff_shifts' then
        v_action := case
            when tg_op = 'INSERT' then 'JORNADA_INICIADA'
            when tg_op = 'DELETE' then 'JORNADA_ELIMINADA'
            when old.check_out_at is null and new.check_out_at is not null
                then 'JORNADA_FINALIZADA'
            else 'JORNADA_EDITADA'
        end;
        v_summary := concat(
            'Entrenador #', coalesce(v_row ->> 'trainer_id', '—'),
            ' · ', coalesce(v_row ->> 'check_in_at', ''),
            case
                when nullif(v_row ->> 'check_out_at', '') is null
                    then ' · jornada activa'
                else ' · salida ' || (v_row ->> 'check_out_at')
            end
        );
    elsif tg_table_name = 'trainers' then
        v_action := case tg_op
            when 'INSERT' then 'ENTRENADOR_CREADO'
            when 'UPDATE' then 'ENTRENADOR_EDITADO'
            else 'ENTRENADOR_ELIMINADO'
        end;
        v_summary := concat(
            coalesce(v_row ->> 'name', 'Entrenador'),
            ' · $', coalesce(v_row ->> 'hourly_rate', '0'), '/hora'
        );
    else
        if tg_op = 'DELETE' then
            return old;
        end if;
        return new;
    end if;

    insert into public.audit_logs(
        gym_id,
        actor_user_id,
        actor_email,
        actor_role,
        action,
        entity_type,
        entity_id,
        summary,
        details
    )
    values (
        v_gym_id,
        v_actor,
        v_email,
        v_role,
        v_action,
        tg_table_name,
        v_row ->> 'id',
        trim(v_summary),
        v_row
    );

    if tg_op = 'DELETE' then
        return old;
    end if;

    return new;
end;
$$;

revoke all on function private.write_staff_accounting_audit()
    from public, anon, authenticated;

