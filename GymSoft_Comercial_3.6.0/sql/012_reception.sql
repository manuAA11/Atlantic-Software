create or replace function private.notify_gym_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_gym_id uuid;
begin
    if tg_op = 'DELETE' then
        v_gym_id := old.gym_id;
    else
        v_gym_id := new.gym_id;
    end if;

    insert into public.gym_events(gym_id, event_type)
    values (v_gym_id, tg_table_name || ':' || lower(tg_op));

    if tg_op = 'DELETE' then
        return old;
    end if;

    return new;
end;
$$;

