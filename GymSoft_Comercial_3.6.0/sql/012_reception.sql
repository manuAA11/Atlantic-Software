create or replace function public.reception_save_client(
    p_gym_id uuid,
    p_client_id bigint,
    p_document text,
    p_first_name text,
    p_last_name text,
    p_phone text default '',
    p_email text default '',
    p_birthdate date default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_client_id bigint;
    v_user_id uuid := (select auth.uid());
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin', 'receptionist']::text[]
    ) then
        raise exception 'No tienes permiso para guardar clientes.'
            using errcode = '42501';
    end if;

    if trim(coalesce(p_document, '')) = ''
       or trim(coalesce(p_first_name, '')) = '' then
        raise exception 'El documento y el nombre son obligatorios.'
            using errcode = '22023';
    end if;

    if p_client_id is null then
        insert into public.clients(
            gym_id,
            document,
            full_name,
            first_name,
            last_name,
            phone,
            email,
            birth_date,
            birthdate,
            emergency_contact,
            medical_notes,
            photo_path,
            active,
            created_by
        )
        values (
            p_gym_id,
            trim(p_document),
            trim(concat_ws(' ', p_first_name, p_last_name)),
            trim(p_first_name),
            trim(coalesce(p_last_name, '')),
            trim(coalesce(p_phone, '')),
            trim(coalesce(p_email, '')),
            p_birthdate,
            p_birthdate,
            '',
            '',
            '',
            true,
            v_user_id
        )
        returning id into v_client_id;
    else
        if not private.client_belongs_to_gym(
            p_client_id,
            p_gym_id
        ) then
            raise exception 'Cliente no encontrado.' using errcode = 'P0002';
        end if;

        update public.clients
        set
            document = trim(p_document),
            full_name = trim(concat_ws(' ', p_first_name, p_last_name)),
            first_name = trim(p_first_name),
            last_name = trim(coalesce(p_last_name, '')),
            phone = trim(coalesce(p_phone, '')),
            email = trim(coalesce(p_email, '')),
            birth_date = p_birthdate,
            birthdate = p_birthdate
        where id = p_client_id
          and gym_id = p_gym_id
        returning id into v_client_id;
    end if;

    return v_client_id;
end;
$$;

