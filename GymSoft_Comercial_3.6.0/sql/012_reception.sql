        left join public.plans p
          on p.id = m.plan_id
         and p.gym_id = m.gym_id
        where m.gym_id = p_gym_id
          and m.client_id = p_client_id
        order by m.paid_at desc, m.id desc
        limit least(greatest(coalesce(p_limit, 30), 1), 100)
