create or replace function public.reception_list_clients(
    p_gym_id uuid,
    p_search text default ''
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_result jsonb;
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin', 'receptionist']::text[]
    ) then
        raise exception 'No tienes permiso para ver estos clientes.'
            using errcode = '42501';
    end if;

    select coalesce(
        jsonb_agg(
            private.membership_snapshot_json(p_gym_id, c.id)
            order by c.first_name, c.last_name, c.id
        ),
        '[]'::jsonb
    )
    into v_result
    from public.clients c
    where c.gym_id = p_gym_id
      and (
          trim(coalesce(p_search, '')) = ''
          or c.document ilike '%' || trim(p_search) || '%'
          or concat_ws(' ', c.first_name, c.last_name)
              ilike '%' || trim(p_search) || '%'
          or coalesce(c.phone, '') ilike '%' || trim(p_search) || '%'
      );

    return v_result;
end;
$$;

