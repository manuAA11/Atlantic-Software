begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin', 'receptionist']::text[]
    ) then
        raise exception 'No tienes permiso para registrar entradas.'
            using errcode = '42501';
    end if;

    v_snapshot := private.membership_snapshot_json(
        p_gym_id,
        p_client_id
    );
    v_membership_id := nullif(
        v_snapshot ->> 'membership_id',
        ''
    )::bigint;

    if v_membership_id is not null then
        perform 1
        from public.memberships m
        where m.id = v_membership_id
          and m.gym_id = p_gym_id
        for update;

        v_snapshot := private.membership_snapshot_json(
            p_gym_id,
            p_client_id
        );
    end if;

    v_allowed := coalesce(
        (v_snapshot ->> 'allowed')::boolean,
        false
    );
    v_result := case
        when v_allowed then 'PERMITIDA'
        else 'DENEGADA'
    end;

    insert into public.checkins(
        gym_id,
        client_id,
        membership_id,
        checkin_at,
        method,
        result,
        notes,
        recorded_by
    )
    values (
        p_gym_id,
        p_client_id,
        v_membership_id,
        v_checkin_at,
        left(trim(coalesce(p_method, 'RECEPCIÓN')), 80),
        v_result,
        '',
        (select auth.uid())
    );

    if v_allowed
       and (v_snapshot ->> 'entry_limit') is not null then
        v_snapshot := jsonb_set(
            v_snapshot,
            '{entries_used}',
            to_jsonb((v_snapshot ->> 'entries_used')::bigint + 1)
        );
        v_snapshot := jsonb_set(
            v_snapshot,
            '{entries_remaining}',
            to_jsonb(
                greatest(
                    (v_snapshot ->> 'entries_remaining')::bigint - 1,
                    0
                )
            )
        );
    end if;

    return v_snapshot || jsonb_build_object(
        'result', v_result,
        'checkin_at', v_checkin_at,
        'override', false
    );
end;
$$;

