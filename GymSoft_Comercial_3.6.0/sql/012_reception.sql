create or replace function public.redeem_reception_invite(
    p_code uuid
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_invite record;
    v_user_id uuid := (select auth.uid());
begin
    if v_user_id is null then
        raise exception 'Debes iniciar sesión.' using errcode = '42501';
    end if;

    if exists (
        select 1
        from public.gym_users gu
        where gu.user_id = v_user_id
    ) then
        raise exception 'Esta cuenta ya pertenece a un gimnasio.'
            using errcode = '23505';
    end if;

    select si.*
    into v_invite
    from public.staff_invites si
    where si.code = p_code
      and si.role = 'receptionist'
      and si.used_at is null
      and si.expires_at > now()
    for update;

    if not found then
        raise exception 'La invitación no existe o ya venció.'
            using errcode = '22023';
    end if;

    insert into public.gym_users(
        gym_id,
        user_id,
        role
    )
    values (
        v_invite.gym_id,
        v_user_id,
        'receptionist'
    );

    update public.staff_invites
    set
        used_by = v_user_id,
        used_at = now()
    where id = v_invite.id;

    return v_invite.gym_id;
end;
$$;

