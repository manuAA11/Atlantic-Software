create or replace function private.insert_store_audit(
    p_gym_id uuid,
    p_actor_user_id uuid,
    p_action text,
    p_entity_type text,
    p_entity_id text,
    p_summary text,
    p_details jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_actor_email text;
    v_actor_role text;
begin
    select coalesce(gu.role, 'authenticated')
    into v_actor_role
    from public.gym_users gu
    where gu.gym_id = p_gym_id
      and gu.user_id = p_actor_user_id
    limit 1;

    v_actor_role := coalesce(v_actor_role, 'system');

    begin
        v_actor_email := coalesce(
            nullif(auth.jwt() ->> 'email', ''),
            case
                when p_actor_user_id is null then 'Sistema'
                else 'Usuario ' || left(p_actor_user_id::text, 8)
            end
        );
    exception when others then
        v_actor_email := case
            when p_actor_user_id is null then 'Sistema'
            else 'Usuario ' || left(p_actor_user_id::text, 8)
        end;
    end;

    insert into public.audit_logs(
        gym_id,
        actor_user_id,
        actor_email,
        actor_role,
        action,
        entity_type,
        entity_id,
        summary,
        details
    )
    values (
        p_gym_id,
        p_actor_user_id,
        v_actor_email,
        v_actor_role,
        p_action,
        p_entity_type,
        p_entity_id,
        trim(coalesce(p_summary, '')),
        coalesce(p_details, '{}'::jsonb)
    );
end;
$$;

