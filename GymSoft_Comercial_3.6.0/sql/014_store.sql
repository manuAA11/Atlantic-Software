create or replace function public.admin_list_store_products(
    p_gym_id uuid,
    p_search text default '',
    p_include_inactive boolean default true
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_search text := trim(coalesce(p_search, ''));
    v_result jsonb;
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin']::text[]
    ) then
        raise exception 'La tienda administrativa es exclusiva del administrador.'
            using errcode = '42501';
    end if;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', p.id,
                'name', p.name,
                'sku', p.sku,
                'sale_price', p.sale_price,
                'stock_quantity', p.stock_quantity,
                'low_stock_threshold', p.low_stock_threshold,
                'active', p.active,
                'stock_status', case
                    when not p.active then 'INACTIVO'
                    when p.stock_quantity = 0 then 'AGOTADO'
                    when p.stock_quantity <= p.low_stock_threshold
                        then 'POCAS UNIDADES'
                    else 'DISPONIBLE'
                end,
                'created_at', p.created_at,
                'updated_at', p.updated_at
            )
            order by p.active desc, p.name
        ),
        '[]'::jsonb
    )
    into v_result
    from public.store_products p
    where p.gym_id = p_gym_id
      and (p_include_inactive or p.active)
      and (
          v_search = ''
          or p.name ilike '%' || v_search || '%'
          or p.sku ilike '%' || v_search || '%'
      );

    return v_result;
end;
$$;

