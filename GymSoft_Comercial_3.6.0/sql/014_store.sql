create or replace function public.admin_save_store_product(
    p_gym_id uuid,
    p_product_id bigint,
    p_name text,
    p_sku text,
    p_sale_price bigint,
    p_stock_quantity integer,
    p_low_stock_threshold integer,
    p_active boolean
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_product_id bigint;
    v_user_id uuid := (select auth.uid());
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin']::text[]
    ) then
        raise exception 'Solo el administrador puede modificar productos.'
            using errcode = '42501';
    end if;

    if trim(coalesce(p_name, '')) = ''
       or coalesce(p_sale_price, -1) < 0
       or coalesce(p_stock_quantity, -1) < 0
       or coalesce(p_low_stock_threshold, -1) < 0 then
        raise exception 'Revisa el nombre, precio y cantidades del producto.'
            using errcode = '22023';
    end if;

    if p_product_id is null then
        insert into public.store_products(
            gym_id,
            name,
            sku,
            sale_price,
            stock_quantity,
            low_stock_threshold,
            active,
            created_by,
            updated_by
        )
        values (
            p_gym_id,
            trim(p_name),
            upper(trim(coalesce(p_sku, ''))),
            p_sale_price,
            p_stock_quantity,
            p_low_stock_threshold,
            coalesce(p_active, true),
            v_user_id,
            v_user_id
        )
        returning id into v_product_id;
    else
        update public.store_products
        set
            name = trim(p_name),
            sku = upper(trim(coalesce(p_sku, ''))),
            sale_price = p_sale_price,
            stock_quantity = p_stock_quantity,
            low_stock_threshold = p_low_stock_threshold,
            active = coalesce(p_active, true),
            updated_by = v_user_id,
            updated_at = now()
        where id = p_product_id
          and gym_id = p_gym_id
        returning id into v_product_id;

        if v_product_id is null then
            raise exception 'Producto no encontrado.'
                using errcode = 'P0002';
        end if;
    end if;

    return v_product_id;
end;
$$;

