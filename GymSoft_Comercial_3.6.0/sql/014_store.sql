create or replace function public.admin_store_finance(
    p_gym_id uuid,
    p_date_from date,
    p_date_to date
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_from date := coalesce(
        p_date_from,
        date_trunc('month', public.gymsoft_today())::date
    );
    v_to date := coalesce(p_date_to, public.gymsoft_today());
    v_result jsonb;
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin']::text[]
    ) then
        raise exception 'Las finanzas son exclusivas del administrador.'
            using errcode = '42501';
    end if;

    if v_from > v_to or (v_to - v_from) > 730 then
        raise exception 'El período de consulta no es válido.'
            using errcode = '22023';
    end if;

    with sales as (
        select
            s.*,
            (s.sold_at at time zone 'America/Bogota')::date as sold_date,
            coalesce(al.actor_email, 'Sistema') as actor_email,
            coalesce(al.actor_role, 'system') as actor_role
        from public.store_sales s
        left join lateral (
            select a.actor_email, a.actor_role
            from public.audit_logs a
            where a.gym_id = s.gym_id
              and a.entity_type = 'store_sales'
              and a.entity_id = s.id::text
              and a.action = 'VENTA_TIENDA'
            order by a.id desc
            limit 1
        ) al on true
        where s.gym_id = p_gym_id
          and (s.sold_at at time zone 'America/Bogota')::date
              between v_from and v_to
    )
    select jsonb_build_object(
        'date_from', v_from,
        'date_to', v_to,
        'store_income', coalesce((
            select sum(total_amount) from sales
        ), 0),
        'sale_count', (select count(*) from sales),
        'average_sale', coalesce((
            select round(avg(total_amount))::bigint from sales
        ), 0),
        'by_product', coalesce((
            select jsonb_agg(
                jsonb_build_object(
                    'label', grouped.product_name,
                    'count', grouped.units_sold,
                    'transactions', grouped.sale_count,
                    'total', grouped.total
                )
                order by grouped.total desc, grouped.product_name
            )
            from (
                select
                    product_name,
                    sum(quantity)::bigint as units_sold,
                    count(*) as sale_count,
                    sum(total_amount)::bigint as total
                from sales
                group by product_name
            ) grouped
        ), '[]'::jsonb),
        'by_method', coalesce((
            select jsonb_agg(
                jsonb_build_object(
                    'label', grouped.payment_method,
                    'count', grouped.sale_count,
                    'total', grouped.total
                )
                order by grouped.total desc, grouped.payment_method
            )
            from (
                select
                    payment_method,
                    count(*) as sale_count,
                    sum(total_amount)::bigint as total
                from sales
                group by payment_method
            ) grouped
        ), '[]'::jsonb),
        'sales', coalesce((
            select jsonb_agg(
                jsonb_build_object(
                    'id', s.id,
                    'product_name', s.product_name,
                    'product_sku', s.product_sku,
                    'quantity', s.quantity,
                    'unit_price', s.unit_price,
