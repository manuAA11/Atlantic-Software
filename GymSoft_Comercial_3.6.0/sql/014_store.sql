create or replace function private.audit_store_product()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_row jsonb;
    v_action text;
    v_actor uuid;
    v_summary text;
    v_details jsonb;
begin
    v_row := case
        when tg_op = 'DELETE' then to_jsonb(old)
        else to_jsonb(new)
    end;
    v_action := case tg_op
        when 'INSERT' then 'PRODUCTO_CREADO'
        when 'UPDATE' then 'PRODUCTO_EDITADO'
        else 'PRODUCTO_ELIMINADO'
    end;
    v_actor := coalesce(
        nullif(v_row ->> 'updated_by', '')::uuid,
        nullif(v_row ->> 'created_by', '')::uuid,
        (select auth.uid())
    );

    if tg_op = 'UPDATE' then
        v_summary := concat(
            new.name,
            ' · Precio $', old.sale_price, ' → $', new.sale_price,
            ' · Stock ', old.stock_quantity, ' → ', new.stock_quantity
        );
        v_details := jsonb_build_object(
            'before', jsonb_build_object(
                'name', old.name,
                'sku', old.sku,
                'sale_price', old.sale_price,
                'stock_quantity', old.stock_quantity,
                'active', old.active
            ),
            'after', jsonb_build_object(
                'name', new.name,
                'sku', new.sku,
                'sale_price', new.sale_price,
                'stock_quantity', new.stock_quantity,
                'active', new.active
            )
        );
    else
        v_summary := concat(
            coalesce(v_row ->> 'name', 'Producto'),
            ' · $', coalesce(v_row ->> 'sale_price', '0'),
            ' · Stock ', coalesce(v_row ->> 'stock_quantity', '0')
        );
        v_details := jsonb_build_object(
            'name', v_row ->> 'name',
            'sku', v_row ->> 'sku',
            'sale_price', v_row ->> 'sale_price',
            'stock_quantity', v_row ->> 'stock_quantity',
            'active', v_row ->> 'active'
        );
    end if;

    perform private.insert_store_audit(
        nullif(v_row ->> 'gym_id', '')::uuid,
        v_actor,
        v_action,
        'store_products',
        v_row ->> 'id',
        v_summary,
        v_details
    );

    if tg_op = 'DELETE' then
        return old;
    end if;
    return new;
end;
$$;

