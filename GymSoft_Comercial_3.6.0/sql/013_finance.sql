create or replace function public.get_finance_dashboard(
    p_gym_id uuid,
    p_date_from date default null,
    p_date_to date default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_from date := coalesce(
        p_date_from,
        date_trunc('month', public.gymsoft_today())::date
    );
    v_to date := coalesce(p_date_to, public.gymsoft_today());
    v_result jsonb;
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin']::text[]
    ) then
        raise exception 'Las finanzas son exclusivas del administrador.'
            using errcode = '42501';
    end if;

    if v_from > v_to then
        raise exception 'La fecha inicial no puede superar la fecha final.'
            using errcode = '22023';
    end if;

    if (v_to - v_from) > 730 then
        raise exception 'El período máximo permitido es de 730 días.'
            using errcode = '22023';
    end if;

    with payments as (
        select
            m.id,
            m.client_id,
            trim(concat_ws(' ', c.first_name, c.last_name))
                as client_name,
            c.document,
            coalesce(p.name, 'Sin plan') as plan_name,
            coalesce(m.amount, m.amount_paid, 0)::bigint as amount,
            coalesce(m.payment_method, 'SIN DEFINIR') as payment_method,
            coalesce(m.payment_reference, '') as payment_reference,
            m.start_date,
            m.end_date,
            m.paid_at,
            m.recorded_by,
            coalesce(
                nullif(a.actor_email, ''),
                case
                    when m.recorded_by is null then 'Anterior al registro'
                    else 'Usuario ' || left(m.recorded_by::text, 8)
                end
            ) as actor_email,
            coalesce(
                nullif(a.actor_role, ''),
                case
                    when m.recorded_by is null then 'system'
                    else 'authenticated'
                end
            ) as actor_role,
            (m.paid_at at time zone 'America/Bogota')::date as paid_date
        from public.memberships m
        join public.clients c
          on c.id = m.client_id
         and c.gym_id = m.gym_id
        left join public.plans p
          on p.id = m.plan_id
         and p.gym_id = m.gym_id
        left join lateral (
            select
                al.actor_email,
                al.actor_role
            from public.audit_logs al
            where al.gym_id = m.gym_id
              and al.entity_type = 'memberships'
              and al.entity_id = m.id::text
              and al.action = 'PAGO_REGISTRADO'
            order by al.created_at asc, al.id asc
            limit 1
        ) a on true
        where m.gym_id = p_gym_id
          and (m.paid_at at time zone 'America/Bogota')::date
              between v_from and v_to
    )
    select jsonb_build_object(
        'date_from', v_from,
        'date_to', v_to,
        'total_income', coalesce((
            select sum(amount) from payments
        ), 0),
        'payment_count', (
            select count(*) from payments
        ),
        'average_payment', coalesce((
            select round(avg(amount))::bigint from payments
        ), 0),
        'by_method', coalesce((
            select jsonb_agg(
                jsonb_build_object(
                    'label', grouped.payment_method,
                    'count', grouped.payment_count,
                    'total', grouped.total
                )
                order by grouped.total desc, grouped.payment_method
            )
            from (
                select
                    payment_method,
                    count(*) as payment_count,
                    sum(amount)::bigint as total
                from payments
                group by payment_method
            ) grouped
        ), '[]'::jsonb),
        'by_plan', coalesce((
            select jsonb_agg(
                jsonb_build_object(
                    'label', grouped.plan_name,
                    'count', grouped.payment_count,
                    'total', grouped.total
                )
                order by grouped.total desc, grouped.plan_name
            )
            from (
                select
                    plan_name,
                    count(*) as payment_count,
                    sum(amount)::bigint as total
                from payments
                group by plan_name
            ) grouped
        ), '[]'::jsonb),
        'by_day', coalesce((
            select jsonb_agg(
                jsonb_build_object(
                    'date', grouped.paid_date,
                    'count', grouped.payment_count,
                    'total', grouped.total
                )
                order by grouped.paid_date
            )
            from (
                select
                    paid_date,
                    count(*) as payment_count,
                    sum(amount)::bigint as total
                from payments
                group by paid_date
            ) grouped
        ), '[]'::jsonb),
        'payments', coalesce((
            select jsonb_agg(
                jsonb_build_object(
                    'id', item.id,
                    'client_id', item.client_id,
                    'client_name', item.client_name,
                    'document', item.document,
                    'plan_name', item.plan_name,
                    'amount', item.amount,
                    'payment_method', item.payment_method,
                    'payment_reference', item.payment_reference,
                    'start_date', item.start_date,
                    'end_date', item.end_date,
                    'paid_at', item.paid_at,
                    'actor_email', item.actor_email,
                    'actor_role', item.actor_role
                )
                order by item.paid_at desc, item.id desc
            )
            from payments item
        ), '[]'::jsonb)
    )
    into v_result;

    return v_result;
end;
$$;

revoke all on function public.get_finance_dashboard(
    uuid, date, date
) from public, anon, authenticated;
grant execute on function public.get_finance_dashboard(
    uuid, date, date
) to authenticated;


create or replace function public.get_audit_logs(
    p_gym_id uuid,
    p_limit integer default 200,
    p_action text default ''
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_result jsonb;
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin']::text[]
    ) then
        raise exception 'La auditoría es exclusiva del administrador.'
            using errcode = '42501';
    end if;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', recent.id,
                'actor_user_id', recent.actor_user_id,
                'actor_email', recent.actor_email,
                'actor_role', recent.actor_role,
                'action', recent.action,
                'entity_type', recent.entity_type,
                'entity_id', recent.entity_id,
                'summary', recent.summary,
                'details', recent.details,
                'created_at', recent.created_at
            )
            order by recent.created_at desc, recent.id desc
        ),
        '[]'::jsonb
    )
    into v_result
    from (
        select al.*
        from public.audit_logs al
        where al.gym_id = p_gym_id
          and (
              trim(coalesce(p_action, '')) = ''
              or al.action = trim(p_action)
          )
        order by al.created_at desc, al.id desc
        limit least(greatest(coalesce(p_limit, 200), 1), 500)
    ) recent;

    return v_result;
end;
$$;

revoke all on function public.get_audit_logs(
    uuid, integer, text
) from public, anon, authenticated;
grant execute on function public.get_audit_logs(
    uuid, integer, text
) to authenticated;

commit;

select
    'PAGOS, FINANZAS Y AUDITORÍA INSTALADOS' as resultado,
    count(*) as registros_de_auditoria
from public.audit_logs;
