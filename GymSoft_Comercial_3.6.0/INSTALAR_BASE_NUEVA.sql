-- Corrige el registro de pagos sin depender de los nombres de las
-- columnas devueltas por la función histórica.
create or replace function public.add_membership_accumulating(
    p_gym_id uuid,
    p_client_id bigint,
    p_plan_id bigint,
    p_requested_start date,
    p_amount bigint,
    p_payment_method text,
    p_payment_reference text,
    p_notes text
)
returns table(
    membership_id bigint,
    start_date date,
    end_date date
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_membership_id bigint;
    v_start_date date;
    v_end_date date;
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin', 'receptionist']::text[]
    ) then
        raise exception 'No tienes permiso para registrar pagos.'
            using errcode = '42501';
    end if;

    if not private.client_belongs_to_gym(p_client_id, p_gym_id)
       or not private.plan_belongs_to_gym(p_plan_id, p_gym_id) then
        raise exception 'El cliente o el plan no pertenece al gimnasio.'
            using errcode = '23503';
    end if;

    if coalesce(p_amount, 0) < 0 then
        raise exception 'El valor pagado no puede ser negativo.'
            using errcode = '22023';
    end if;

    -- Ejecutar la función original y descartar su forma de retorno.
    -- De este modo funciona aunque sus columnas se llamen de otra manera.
    perform 1
    from public.add_membership_accumulating_internal(
        p_gym_id,
        p_client_id,
        p_plan_id,
        p_requested_start,
        p_amount,
        p_payment_method,
        p_payment_reference,
        p_notes
    );

    select
        m.id,
        m.start_date,
        m.end_date
    into
        v_membership_id,
        v_start_date,
        v_end_date
    from public.memberships m
    where m.gym_id = p_gym_id
      and m.client_id = p_client_id
    order by m.id desc
    limit 1;

    if v_membership_id is null then
        raise exception 'La función de pagos no creó la membresía.'
            using errcode = 'P0001';
    end if;

    update public.memberships
    set recorded_by = (select auth.uid())
    where id = v_membership_id
      and gym_id = p_gym_id;

    return query
    select v_membership_id, v_start_date, v_end_date;
end;
$$;

