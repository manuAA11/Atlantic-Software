    p_gym_id uuid,
    p_product_id bigint,
    p_quantity integer,
    p_payment_method text,
    p_payment_reference text,
    p_customer_name text,
    p_notes text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_product record;
    v_sale_id bigint;
    v_sold_at timestamptz;
    v_total bigint;
    v_remaining integer;
    v_payment_method text := upper(
        coalesce(nullif(trim(p_payment_method), ''), 'EFECTIVO')
    );
    v_user_id uuid := (select auth.uid());
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin', 'receptionist']::text[]
    ) then
        raise exception 'No tienes permiso para registrar ventas.'
            using errcode = '42501';
    end if;

    if coalesce(p_quantity, 0) <= 0 then
        raise exception 'La cantidad debe ser mayor que cero.'
            using errcode = '22023';
    end if;

    if v_payment_method not in (
        'EFECTIVO',
        'TRANSFERENCIA',
        'TARJETA',
        'OTRO'
    ) then
        raise exception 'El método de pago no es válido.'
            using errcode = '22023';
    end if;

    select p.*
    into v_product
    from public.store_products p
    where p.id = p_product_id
      and p.gym_id = p_gym_id
    for update;

    if not found or not coalesce(v_product.active, false) then
        raise exception 'El producto no existe o está desactivado.'
            using errcode = 'P0002';
    end if;

    if v_product.stock_quantity < p_quantity then
        raise exception 'Existencias insuficientes. Disponibles: %.',
            v_product.stock_quantity
            using errcode = '22023';
    end if;

    v_total := v_product.sale_price * p_quantity;
    v_remaining := v_product.stock_quantity - p_quantity;

    update public.store_products
    set
        stock_quantity = v_remaining,
        updated_by = v_user_id,
        updated_at = now()
    where id = v_product.id
      and gym_id = p_gym_id;

    insert into public.store_sales(
        gym_id,
        product_id,
        product_name,
        product_sku,
        quantity,
        unit_price,
        total_amount,
        payment_method,
        payment_reference,
        customer_name,
        notes,
        sold_by
    )
    values (
        p_gym_id,
        v_product.id,
        v_product.name,
        v_product.sku,
        p_quantity,
        v_product.sale_price,
        v_total,
        v_payment_method,
        trim(coalesce(p_payment_reference, '')),
        trim(coalesce(p_customer_name, '')),
        trim(coalesce(p_notes, '')),
        v_user_id
    )
    returning id, sold_at into v_sale_id, v_sold_at;

    return jsonb_build_object(
        'sale_id', v_sale_id,
        'product_id', v_product.id,
        'product_name', v_product.name,
        'quantity', p_quantity,
        'unit_price', v_product.sale_price,
        'total_amount', v_total,
        'stock_remaining', v_remaining,
        'sold_at', v_sold_at
    );
end;
$$;

