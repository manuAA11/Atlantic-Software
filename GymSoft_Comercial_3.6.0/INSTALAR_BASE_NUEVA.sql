returns jsonb
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
declare
    v_gym_id uuid;
    v_tables jsonb;
    v_row jsonb;
    v_old_id text;
    v_new_id bigint;
    v_client_id bigint;
    v_plan_id bigint;
    v_membership_id bigint;
