    if p_amount is null or p_amount <= 0 or p_amount > 1000000000000000 then
        raise exception 'El valor del gasto debe ser mayor que cero.'
            using errcode = '22023';
    end if;

    if v_method = '' then
        v_method := 'Efectivo';
    end if;

    insert into public.accounting_expenses(
        gym_id,
        expense_date,
        category,
        description,
        vendor,
        amount,
        payment_method,
        payment_reference,
        receipt_reference,
        notes,
        recorded_by
    )
    values (
        p_gym_id,
        p_expense_date,
        v_category,
        v_description,
        v_vendor,
        p_amount,
        v_method,
        v_payment_reference,
        v_receipt_reference,
        v_notes,
        (select auth.uid())
    )
    returning id into v_id;

    return v_id;
end;
$$;

