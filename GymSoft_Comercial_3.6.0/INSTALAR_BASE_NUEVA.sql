create or replace function public.reception_register_checkin(
    p_gym_id uuid,
    p_client_id bigint,
    p_method text default 'RECEPCIÓN'
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_snapshot jsonb;
    v_membership_id bigint;
    v_allowed boolean;
    v_result text;
    v_checkin_at timestamptz := public.gymsoft_now();
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin', 'receptionist']::text[]
    ) then
        raise exception 'No tienes permiso para registrar entradas.'
            using errcode = '42501';
    end if;

    v_snapshot := private.membership_snapshot_json(
        p_gym_id,
        p_client_id
    );
    v_membership_id := nullif(
        v_snapshot ->> 'membership_id',
        ''
    )::bigint;

    if v_membership_id is not null then
        perform 1
        from public.memberships m
        where m.id = v_membership_id
          and m.gym_id = p_gym_id
        for update;

        v_snapshot := private.membership_snapshot_json(
            p_gym_id,
            p_client_id
        );
    end if;

    v_allowed := coalesce(
        (v_snapshot ->> 'allowed')::boolean,
        false
    );
    v_result := case
        when v_allowed then 'PERMITIDA'
        else 'DENEGADA'
    end;

    insert into public.checkins(
        gym_id,
        client_id,
        membership_id,
        checkin_at,
        method,
        result,
        notes,
        recorded_by
    )
    values (
        p_gym_id,
        p_client_id,
        v_membership_id,
        v_checkin_at,
        left(trim(coalesce(p_method, 'RECEPCIÓN')), 80),
        v_result,
        '',
        (select auth.uid())
    );

    if v_allowed
       and (v_snapshot ->> 'entry_limit') is not null then
        v_snapshot := jsonb_set(
            v_snapshot,
            '{entries_used}',
            to_jsonb((v_snapshot ->> 'entries_used')::bigint + 1)
        );
        v_snapshot := jsonb_set(
            v_snapshot,
            '{entries_remaining}',
            to_jsonb(
                greatest(
                    (v_snapshot ->> 'entries_remaining')::bigint - 1,
