create or replace function public.get_finance_dashboard(
    p_gym_id uuid,
    p_date_from date default null,
    p_date_to date default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_from date := coalesce(
        p_date_from,
        date_trunc('month', public.gymsoft_today())::date
    );
    v_to date := coalesce(p_date_to, public.gymsoft_today());
    v_result jsonb;
begin
    if not private.user_has_gym_role(
        p_gym_id,
        array['admin']::text[]
    ) then
        raise exception 'Las finanzas son exclusivas del administrador.'
            using errcode = '42501';
    end if;

    if v_from > v_to then
        raise exception 'La fecha inicial no puede superar la fecha final.'
            using errcode = '22023';
    end if;

    if (v_to - v_from) > 730 then
        raise exception 'El período máximo permitido es de 730 días.'
            using errcode = '22023';
    end if;

    with payments as (
        select
            m.id,
            m.client_id,
            trim(concat_ws(' ', c.first_name, c.last_name))
                as client_name,
            c.document,
            coalesce(p.name, 'Sin plan') as plan_name,
            coalesce(m.amount, m.amount_paid, 0)::bigint as amount,
            coalesce(m.payment_method, 'SIN DEFINIR') as payment_method,
            coalesce(m.payment_reference, '') as payment_reference,
            m.start_date,
            m.end_date,
            m.paid_at,
            m.recorded_by,
            coalesce(
                nullif(a.actor_email, ''),
                case
                    when m.recorded_by is null then 'Anterior al registro'
                    else 'Usuario ' || left(m.recorded_by::text, 8)
                end
            ) as actor_email,
            coalesce(
                nullif(a.actor_role, ''),
                case
                    when m.recorded_by is null then 'system'
                    else 'authenticated'
                end
            ) as actor_role,
            (m.paid_at at time zone 'America/Bogota')::date as paid_date
        from public.memberships m
        join public.clients c
          on c.id = m.client_id
         and c.gym_id = m.gym_id
        left join public.plans p
          on p.id = m.plan_id
         and p.gym_id = m.gym_id
        left join lateral (
            select
                al.actor_email,
                al.actor_role
            from public.audit_logs al
            where al.gym_id = m.gym_id
              and al.entity_type = 'memberships'
              and al.entity_id = m.id::text
              and al.action = 'PAGO_REGISTRADO'
            order by al.created_at asc, al.id asc
            limit 1
        ) a on true
        where m.gym_id = p_gym_id
          and (m.paid_at at time zone 'America/Bogota')::date
              between v_from and v_to
    )
    select jsonb_build_object(
