                'hire_date', w.hire_date,
                'notes', w.notes,
                'active', w.active,
                'current_check_in', w.current_check_in,
                'period_seconds', w.period_seconds,
                'estimated_pay', w.estimated_pay
            ) order by w.active desc, w.name)
            from worker_values w
        ), '[]'::jsonb),
        'shifts', coalesce((
            select jsonb_agg(jsonb_build_object(
                'id', s.id,
                'trainer_id', s.trainer_id,
