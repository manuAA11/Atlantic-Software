create or replace function private.write_audit_log()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_row jsonb;
    v_old_row jsonb;
    v_gym_id uuid;
    v_actor_user_id uuid;
    v_actor_email text := 'Sistema';
    v_actor_role text := 'system';
    v_action text;
    v_entity_id text;
    v_summary text := '';
    v_details jsonb := '{}'::jsonb;
begin
    if tg_op = 'DELETE' then
        v_row := to_jsonb(old);
    else
        v_row := to_jsonb(new);
    end if;

    if tg_op = 'UPDATE' then
        v_old_row := to_jsonb(old);

        -- El envoltorio de pagos completa recorded_by justo después
        -- de insertar. Ese cambio técnico no debe crear un log duplicado.
        if tg_table_name = 'memberships'
           and (v_row - 'recorded_by') = (v_old_row - 'recorded_by') then
            return new;
        end if;
    end if;

    v_gym_id := nullif(v_row ->> 'gym_id', '')::uuid;
    v_actor_user_id := coalesce(
        nullif(v_row ->> 'recorded_by', '')::uuid,
        (select auth.uid())
    );

    if v_actor_user_id is not null then
        select coalesce(gu.role, 'authenticated')
        into v_actor_role
        from public.gym_users gu
        where gu.gym_id = v_gym_id
          and gu.user_id = v_actor_user_id
        limit 1;

        v_actor_role := coalesce(v_actor_role, 'authenticated');
    end if;

    begin
        v_actor_email := coalesce(
            nullif(auth.jwt() ->> 'email', ''),
            case
                when v_actor_user_id is null then 'Sistema'
                else 'Usuario ' || left(v_actor_user_id::text, 8)
            end
        );
    exception when others then
        v_actor_email := case
            when v_actor_user_id is null then 'Sistema'
            else 'Usuario ' || left(v_actor_user_id::text, 8)
        end;
    end;

    if tg_table_name = 'memberships' then
        v_action := case tg_op
            when 'INSERT' then 'PAGO_REGISTRADO'
            when 'UPDATE' then 'PAGO_EDITADO'
            else 'PAGO_ELIMINADO'
        end;
        v_entity_id := v_row ->> 'id';
        v_summary := concat(
            'Pago de $',
            coalesce(v_row ->> 'amount', v_row ->> 'amount_paid', '0'),
            ' para el cliente #',
            coalesce(v_row ->> 'client_id', '—')
        );
        v_details := jsonb_build_object(
            'client_id', v_row ->> 'client_id',
            'plan_id', v_row ->> 'plan_id',
            'start_date', v_row ->> 'start_date',
            'end_date', v_row ->> 'end_date',
            'amount', coalesce(
                v_row ->> 'amount',
                v_row ->> 'amount_paid',
                '0'
            ),
            'payment_method', coalesce(
                v_row ->> 'payment_method',
                ''
            )
        );
    elsif tg_table_name = 'checkins' then
        v_action := 'ENTRADA_REGISTRADA';
        v_entity_id := v_row ->> 'id';
        v_summary := concat(
            'Entrada ',
            coalesce(v_row ->> 'result', 'registrada'),
            ' para el cliente #',
            coalesce(v_row ->> 'client_id', '—')
        );
        v_details := jsonb_build_object(
            'client_id', v_row ->> 'client_id',
            'result', v_row ->> 'result',
            'method', v_row ->> 'method'
        );
    elsif tg_table_name = 'clients' then
        v_action := case tg_op
            when 'INSERT' then 'CLIENTE_CREADO'
            when 'UPDATE' then 'CLIENTE_EDITADO'
            else 'CLIENTE_ELIMINADO'
        end;
        v_entity_id := v_row ->> 'id';
        v_summary := concat(
            coalesce(v_row ->> 'first_name', ''),
            ' ',
            coalesce(v_row ->> 'last_name', ''),
            ' · ',
            coalesce(v_row ->> 'document', '')
        );
        v_details := jsonb_build_object(
            'document', v_row ->> 'document',
            'client_name', trim(concat_ws(
                ' ',
                v_row ->> 'first_name',
                v_row ->> 'last_name'
            ))
        );
    elsif tg_table_name = 'plans' then
        v_action := case tg_op
            when 'INSERT' then 'PLAN_CREADO'
            when 'UPDATE' then 'PLAN_EDITADO'
            else 'PLAN_ELIMINADO'
        end;
        v_entity_id := v_row ->> 'id';
        v_summary := concat(
            coalesce(v_row ->> 'name', 'Plan'),
            ' · $',
            coalesce(v_row ->> 'price', '0')
        );
        v_details := jsonb_build_object(
            'name', v_row ->> 'name',
            'duration_days', v_row ->> 'duration_days',
            'price', v_row ->> 'price',
            'active', v_row ->> 'active'
        );
    elsif tg_table_name = 'gym_users' then
        v_action := case tg_op
            when 'INSERT' then 'USUARIO_AGREGADO'
            when 'UPDATE' then 'USUARIO_EDITADO'
            else 'USUARIO_ELIMINADO'
        end;
        v_entity_id := v_row ->> 'user_id';
        v_summary := concat(
            'Usuario ',
            left(coalesce(v_row ->> 'user_id', ''), 8),
            ' · ',
            coalesce(v_row ->> 'role', '')
        );
        v_details := jsonb_build_object(
            'user_id', v_row ->> 'user_id',
            'role', v_row ->> 'role'
        );
    else
        if tg_op = 'DELETE' then
            return old;
        end if;

        return new;
    end if;

    insert into public.audit_logs(
        gym_id,
        actor_user_id,
        actor_email,
        actor_role,
        action,
        entity_type,
        entity_id,
        summary,
        details
    )
    values (
        v_gym_id,
        v_actor_user_id,
        v_actor_email,
        v_actor_role,
        v_action,
        tg_table_name,
        v_entity_id,
        trim(v_summary),
        v_details
    );

    if tg_op = 'DELETE' then
        return old;
    end if;

    return new;
end;
$$;

