 'users',coalesce((select jsonb_agg(jsonb_build_object('email',a.email,'role',u.role,'enabled',u.enabled) order by a.email)
  from public.gym_users u join auth.users a on a.id=u.user_id where u.gym_id=p_gym_id),'[]'),
