  'Tiquetera trasladada sin nuevo cobro. '||trim(coalesce(p_notes,'')),auth.uid(),p_request_id,
  p_start::timestamp at time zone private.current_timezone()) returning id into mid;
 return query select mid,p_start,ending;
end $$;
