create or replace function private.preserve_ticket_history() returns trigger
language plpgsql security definer set search_path='' as $$
begin
 if (old.ticket_consumed is not null or exists(select 1 from public.ticket_daily_consumptions where checkin_id=old.id))
 and row(new.gym_id,new.client_id,new.membership_id,new.checkin_at,new.result,new.local_date,new.ticket_consumed,new.already_consumed_today)
 is distinct from row(old.gym_id,old.client_id,old.membership_id,old.checkin_at,old.result,old.local_date,old.ticket_consumed,old.already_consumed_today) then
  raise exception 'No se puede cambiar el consumo de una entrada registrada. Añade una nota de corrección para conservar la trazabilidad.';
 end if; return new;
end $$;
drop trigger if exists preserve_ticket_history on public.checkins;
