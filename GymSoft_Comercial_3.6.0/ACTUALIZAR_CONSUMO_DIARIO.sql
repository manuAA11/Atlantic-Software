create or replace function private.consume_daily_ticket() returns trigger
language plpgsql security definer set search_path='' as $$
declare m record; used bigint; importing boolean; first_id bigint;
begin
 importing:=exists(select 1 from private.ticket_import_context where transaction_id=txid_current() and gym_id=new.gym_id);
 new.local_date:=coalesce(case when importing then new.local_date end,
  (new.checkin_at at time zone private.gym_timezone(new.gym_id))::date);
 if not importing then new.ticket_consumed:=false; new.already_consumed_today:=false; end if;
 if new.result<>'PERMITIDA' or new.membership_id is null then return new; end if;
 perform pg_catalog.pg_advisory_xact_lock(new.client_id);
 select mm.*,coalesce(mm.entry_limit,p.entry_limit) as quota into m
 from public.memberships mm join public.plans p on p.id=mm.plan_id and p.gym_id=mm.gym_id
 where mm.id=new.membership_id and mm.gym_id=new.gym_id and mm.client_id=new.client_id for update of mm;
 if not found then raise exception 'La membresía no pertenece a este cliente y gimnasio.'; end if;
 if m.quota is null then return new; end if;
 if importing then
  if m.ticket_consumption_archive is null then
   -- Older backup: each historical approved visit consumed one entry. Preserve that balance.
   insert into public.ticket_daily_consumptions(gym_id,client_id,membership_id,local_date,checkin_id,legacy,created_at)
   values(new.gym_id,new.client_id,new.membership_id,new.local_date,new.id,true,new.checkin_at)
   on conflict(gym_id,client_id,membership_id,local_date) do update set units=public.ticket_daily_consumptions.units+1;
  end if;
  return new;
 end if;
 if new.notes='Autorización manual del administrador' then return new; end if;
 if m.payment_status<>'posted' or new.local_date not between m.start_date and m.end_date
 or not exists(select 1 from public.clients where id=new.client_id and gym_id=new.gym_id and active) then
  raise exception 'El cliente o su tiquetera no permiten el ingreso.';
 end if;
 if private.ticket_consumed_on(new.gym_id,new.client_id,new.membership_id,new.local_date) then
  new.already_consumed_today:=true; return new;
 end if;
 used:=private.ticket_consumption_units(new.gym_id,new.membership_id)+m.initial_entries_used;
 if used>=m.quota then raise exception 'La tiquetera no tiene entradas disponibles.'; end if;
 insert into public.ticket_daily_consumptions(gym_id,client_id,membership_id,local_date,checkin_id,created_at)
 values(new.gym_id,new.client_id,new.membership_id,new.local_date,new.id,new.checkin_at)
 on conflict(gym_id,client_id,membership_id,local_date) do nothing returning id into first_id;
 new.ticket_consumed:=first_id is not null;
 new.already_consumed_today:=first_id is null;
 return new;
end $$;
