create or replace function private.restore_ticket_archive() returns trigger
language plpgsql security definer set search_path='' as $$
declare item jsonb;
begin
 if new.ticket_consumption_archive is null then return new; end if;
 if jsonb_typeof(new.ticket_consumption_archive)<>'array' or jsonb_array_length(new.ticket_consumption_archive)>10000 then
  raise exception 'El respaldo de consumo de tiquetera no es válido.';
 end if;
 for item in select value from jsonb_array_elements(new.ticket_consumption_archive) loop
  insert into public.ticket_daily_consumptions(gym_id,client_id,membership_id,local_date,units,legacy,created_at)
  values(new.gym_id,new.client_id,new.id,(item->>'local_date')::date,(item->>'units')::bigint,
   coalesce((item->>'legacy')::boolean,false),coalesce((item->>'created_at')::timestamptz,now()));
 end loop; return new;
end $$;
