CREATE OR REPLACE FUNCTION private.membership_snapshot_json(p_gym_id uuid, p_client_id bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
    v_client record;
    v_membership_id bigint;
    v_start_date date;
    v_end_date date;
    v_entry_limit bigint;
    v_entries_used bigint := 0;
    v_plan_name text := 'Sin plan';
    v_today date := private.gym_local_date(p_gym_id);
    v_consumed boolean := false;
    v_allowed boolean := false;
    v_status text := 'VENCIDO';
begin
    select
        c.id,
        c.document,
        c.first_name,
        c.last_name,
        c.phone,
        c.email,
        coalesce(c.birthdate, c.birth_date) as birthdate,
        c.biometric_identifier, c.active
    into v_client
    from public.clients c
    where c.id = p_client_id
      and c.gym_id = p_gym_id;

    if not found then
        raise exception 'Cliente no encontrado.' using errcode = 'P0002';
    end if;

    select
        m.id,
        m.start_date,
        m.end_date,
        coalesce(m.entry_limit, p.entry_limit),
        coalesce(p.name, 'Sin plan')
    into
        v_membership_id,
        v_start_date,
        v_end_date,
        v_entry_limit,
        v_plan_name
    from public.memberships m
    left join public.plans p
      on p.id = m.plan_id
     and p.gym_id = m.gym_id
    where m.gym_id = p_gym_id AND m.payment_status = 'posted' /* ZTATTUZ_PAYMENT_VOID_FILTER_V1 */
      and m.client_id = p_client_id
    order by
        case
            when v_today between m.start_date and m.end_date then 0
            else 1
        end,
        case when private.ticket_consumed_on(p_gym_id,p_client_id,m.id,v_today) then 0 else 1 end,
        m.end_date desc,
        m.id desc
    limit 1;

    if v_membership_id is not null and v_entry_limit is not null then
        select private.ticket_consumption_units(p_gym_id,v_membership_id) + m.initial_entries_used
        into v_entries_used from public.memberships m where m.gym_id=p_gym_id and m.id=v_membership_id;
        v_consumed:=private.ticket_consumed_on(p_gym_id,p_client_id,v_membership_id,v_today);
    end if;

    if not coalesce(v_client.active, true) then
        v_status := 'INACTIVO';
    elsif v_membership_id is null then
        v_status := 'VENCIDO';
    elsif not (v_today between v_start_date and v_end_date) then
        v_status := 'VENCIDO';
    elsif v_entry_limit is not null
          and v_entries_used >= v_entry_limit and not v_consumed then
        v_status := 'SIN ENTRADAS';
    else
        v_status := 'AL DÍA';
        v_allowed := true;
    end if;

    return jsonb_build_object(
        'already_consumed_today',v_consumed,'local_date',v_today,
        'id', v_client.id, 'biometric_identifier', v_client.biometric_identifier,
        'document', v_client.document,
        'first_name', v_client.first_name,
        'last_name', v_client.last_name,
        'client_name', trim(
            concat_ws(' ', v_client.first_name, v_client.last_name)
        ),
        'phone', coalesce(v_client.phone, ''),
        'email', coalesce(v_client.email, ''),
        'birthdate', coalesce(v_client.birthdate::text, ''),
        'active', coalesce(v_client.active, true),
        'status', v_status,
        'allowed', v_allowed,
        'membership_id', v_membership_id,
        'membership_start', coalesce(v_start_date::text, ''),
        'membership_end', coalesce(v_end_date::text, ''),
        'plan_name', v_plan_name,
        'entry_limit', v_entry_limit,
        'entries_used', v_entries_used,
        'entries_remaining', case
            when v_entry_limit is null then null
            else greatest(v_entry_limit - v_entries_used, 0)
        end
    );
end;
$function$;

create or replace function private.daily_register_checkin(p_gym_id uuid,p_client_id bigint,p_method text,p_override boolean default false)
returns jsonb language plpgsql security definer set search_path='' as $$
declare s jsonb; ch public.checkins; allowed boolean;
begin
 if auth.uid() is null or not private.user_has_gym_role(p_gym_id,array['admin','receptionist'])
 or (p_override and not private.user_has_gym_role(p_gym_id,array['admin'])) then
  raise exception 'No tienes permiso para registrar esta entrada.' using errcode='42501';
 end if;
 perform pg_catalog.pg_advisory_xact_lock(p_client_id);
 perform 1 from public.clients where gym_id=p_gym_id and id=p_client_id for update;
 s:=private.membership_snapshot_json(p_gym_id,p_client_id);
 allowed:=coalesce((s->>'allowed')::boolean,false);
 insert into public.checkins(gym_id,client_id,membership_id,checkin_at,method,result,notes,recorded_by)
 values(p_gym_id,p_client_id,nullif(s->>'membership_id','')::bigint,private.gym_server_now(),
 left(trim(coalesce(p_method,'MANUAL')),80),case when allowed or p_override then 'PERMITIDA' else 'DENEGADA' end,
 case when p_override and not allowed then 'Autorización manual del administrador' else '' end,auth.uid()) returning * into ch;
 if ch.ticket_consumed then
  s:=s||jsonb_build_object('entries_used',(s->>'entries_used')::bigint+1,
    'entries_remaining',greatest((s->>'entries_remaining')::bigint-1,0));
 end if;
 return s||jsonb_build_object('result',ch.result,'checkin_id',ch.id,'checkin_at',ch.checkin_at,
 'override',p_override and not allowed,'ticket_consumed',ch.ticket_consumed,
 'already_consumed_today',ch.already_consumed_today,'local_date',ch.local_date);
end $$;
revoke all on function private.daily_register_checkin(uuid,bigint,text,boolean) from public,anon,authenticated;
